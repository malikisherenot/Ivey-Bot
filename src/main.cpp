    float activeTps() {
        auto& bot = Bot::get();
        if (!bot.cfg.frameAccurate) return 240.f;

        // A loaded macro brings its TPS, but it only applies once the bot is really
        // recording or replaying. Until then the game runs normally.
        if (bot.backup.active && bot.mode == Mode::Idle) return 240.f;

        return static_cast<float>(bot.cfg.tps);
    }

    // Frame = time in the level * TPS. The game's own step counter stays at
    // 240 per second, so it can't be used once TPS changes.
    uint32_t frameOf(GJBaseGameLayer* gl) {
        // Macros from other bots count the game's own steps (same as xdBot does).
        auto& bot = Bot::get();
        if (bot.mode == Mode::Replay && (bot.macro.flags & 4)) {
            int steps = gl->m_gameState.m_currentProgress;
            return steps < 0 ? 0u : static_cast<uint32_t>(steps);
        }

        int frame = static_cast<int>(gl->m_gameState.m_levelTime * static_cast<double>(activeTps())) + 1;
        return frame < 0 ? 0u : static_cast<uint32_t>(frame);
    }

    // How many multi-activate dash orbs (green, pink, black) overlap the player.
    int overlappingDashOrbs(GJBaseGameLayer* gl) {
        if (!gl || !gl->m_player1 || !gl->m_objectLayer) return 0;

        CCRect playerRect = gl->m_player1->boundingBox();
        int multi = 0;

        auto batches = gl->m_objectLayer->getChildren();
        if (!batches) return 0;

        for (auto batch : CCArrayExt<CCNode*>(batches)) {
            if (!batch || !batch->getChildren()) continue;
            for (auto child : CCArrayExt<CCNode*>(batch->getChildren())) {
                auto obj = typeinfo_cast<EffectGameObject*>(child);
                if (!obj) continue;

                int id = obj->m_objectID;
                if (id != 1704 && id != 1751 && id != 1330) continue;
                if (!playerRect.intersectsRect(obj->boundingBox())) continue;

                if (obj->m_isNoMultiActivate) return 0; // hold orbs can't be clicked twice
                if (obj->m_isMultiActivate) ++multi;
            }
        }
        return multi;
    }

    // Clicks to fit into one frame for this press (1 = a normal click).
    int swiftClickCount(GJBaseGameLayer* gl) {
        auto& c = Bot::get().cfg;

        if (c.swiftSmart) {
            int orbs = overlappingDashOrbs(gl);
            if (orbs > 0) return orbs + 1;
        }
        return c.swift ? std::max(1, c.swiftClicks) : 1;
    }

    // True while either player is a wave.
    bool waveActive(GJBaseGameLayer* gl) {
        if (gl->m_player1 && gl->m_player1->m_isDart) return true;
        auto p2 = gl->m_player2;
        return p2 && p2->isVisible() && p2->m_isDart;
    }

    bool inPlay(GJBaseGameLayer* gl) {
        return typeinfo_cast<PlayLayer*>(gl) != nullptr;
    }

