    CCTexture2D* embeddedTexture() {
        auto cache = CCTextureCache::get();
        if (auto tex = cache->textureForKey("ivey-menu-embedded")) return tex;

        auto img = new CCImage();
        if (!img->initWithImageData(const_cast<unsigned char*>(ivey::ICON_PNG), static_cast<int>(ivey::ICON_PNG_SIZE))) {
            img->release();
            return nullptr;
        }
        auto tex = cache->addUIImage(img, "ivey-menu-embedded");
        img->release();
        return tex;
    }

    CCSprite* makeIcon() {
        // Use the resource file when it really exists, otherwise the built-in copy.
        std::string name = std::string("ivey-menu.png"_spr);
        auto utils = CCFileUtils::get();
        std::string full = utils->fullPathForFilename(name.c_str(), false);

        CCSprite* spr = nullptr;
        if (full != name && utils->isFileExist(full.c_str())) {
            spr = CCSprite::create(name.c_str());
        }
        if (!spr) {
            if (auto tex = embeddedTexture()) spr = CCSprite::createWithTexture(tex);
        }
        if (!spr) return nullptr;

        spr->setScale(BUTTON_SIZE / spr->getContentSize().width);
        return spr;
    }

